import { beforeAll, afterAll, describe, it, expect } from "vitest";
import { mkdirSync, writeFileSync } from "node:fs";
import { prisma } from "@fii/database";
import { createSubscriber, getSubscriber } from "../src/services/subscriber.service.js";
import { subscriberCreateBody, subscriberUpdateBody } from "../src/validators.js";
import { processRun } from "../../../workers/billing-worker/src/generate.js";
import { createInvoice, updateInvoice, cancelInvoice } from "../../billing-service/src/services/invoice.service.js";
import { buildInvoicePdfBuffer } from "@fii/pdf";
const suite = process.env.RUN_INTEGRATION_TESTS === "true" ? describe : describe.skip;
suite("subscriber PO snapshot through billing and PDF", () => {
  let tenantId = "", customerId = "", otherCustomerId = "", planId = "", subscriberId = "", actorId = "";
  beforeAll(async () => {
    tenantId = (await prisma.tenant.create({ data: { name: "PO TEST COMPANY", subdomain: `po-${Date.now()}`, stateCode: "33" } })).id;
    customerId = (await prisma.customer.create({ data: { tenantId, name: "PO TEST CUSTOMER", code: "C-1", phone: "9000000001", stateCode: "33" } })).id;
    otherCustomerId = (await prisma.customer.create({ data: { tenantId, name: "Other customer", code: "C-2" } })).id;
    actorId = (await prisma.user.create({ data: { tenantId, email: "po-test@example.test", name: "Tester", passwordHash: "not-a-login" } })).id;
    planId = (await prisma.plan.create({ data: { tenantId, code: "PLAN", name: "Internet", price: "100", gstRate: "18", planType: "PREPAID" } })).id;
    await prisma.financialYear.create({ data: { tenantId, code: "2026-27", startDate: new Date("2026-04-01"), endDate: new Date("2027-03-31T23:59:59Z"), isActive: true } });
    subscriberId = (await createSubscriber(tenantId, subscriberCreateBody.parse({ customerId, subscriberType: "PREPAID", activationDate: "2026-10-01", plans: [{ planId }], poNumber: " PO/2026/ORIGINAL-001 " }))).id;
  });
  afterAll(async () => {
    await prisma.billingRunItem.deleteMany({ where: { billingRun: { tenantId } } });
    await prisma.billingRun.deleteMany({ where: { tenantId } });
    await prisma.outboxEvent.deleteMany({ where: { tenantId } });
    await prisma.invoiceItem.deleteMany({ where: { invoice: { tenantId } } });
    await prisma.invoice.deleteMany({ where: { tenantId } });
    await prisma.subscriberPlan.deleteMany({ where: { tenantId } });
    await prisma.subscriber.deleteMany({ where: { tenantId } });
    await prisma.plan.deleteMany({ where: { tenantId } });
    await prisma.customer.deleteMany({ where: { tenantId } });
    await prisma.user.deleteMany({ where: { tenantId } });
    await prisma.numberSeries.deleteMany({ where: { tenantId } });
    await prisma.financialYear.deleteMany({ where: { tenantId } });
    await prisma.tenant.deleteMany({ where: { id: tenantId } });
    await prisma.$disconnect();
  });
  it("saves, validates, snapshots, preserves issued POs, and renders the full PO", async () => {
    expect((await getSubscriber(tenantId, subscriberId)).poNumber).toBe("PO/2026/ORIGINAL-001");
    expect(subscriberUpdateBody.parse({ billingCycleMonths: 3 })).not.toHaveProperty("poNumber");
    expect(subscriberUpdateBody.parse({ subscriberType: "POSTPAID" })).toEqual({ subscriberType: "POSTPAID" });
    expect(subscriberUpdateBody.safeParse({ subscriberType: "OTHER" }).success).toBe(false);
    expect(subscriberUpdateBody.parse({ poNumber: " " }).poNumber).toBeNull();
    expect(subscriberUpdateBody.safeParse({ poNumber: "x".repeat(101) }).success).toBe(false);
    const spec = { tenantId, cycleType: "PREPAID" as const, periodStart: new Date("2026-10-01"), periodEnd: new Date("2026-10-31") };
    await processRun(spec);
    const first = await prisma.invoice.findFirstOrThrow({ where: { tenantId, invoiceType: "SUBSCRIPTION" } });
    expect(first.poNumber).toBe("PO/2026/ORIGINAL-001");
    const nextPo = "PO/2026/NEXT-002-LONG-REFERENCE-ABCDEFGHIJKLMNOPQRSTUVWXYZ-0123456789";
    await prisma.subscriber.update({ where: { id: subscriberId }, data: subscriberUpdateBody.parse({ poNumber: nextPo }) });
    await processRun(spec);
    expect((await prisma.invoice.findUniqueOrThrow({ where: { id: first.id } })).poNumber).toBe("PO/2026/ORIGINAL-001");
    await processRun({ ...spec, periodStart: new Date("2026-11-01"), periodEnd: new Date("2026-11-30") });
    const next = await prisma.invoice.findFirstOrThrow({ where: { tenantId, periodStart: new Date("2026-11-01") } });
    expect(next.poNumber).toBe(nextPo);
    const manual = await createInvoice(tenantId, actorId, { customerId, subscriberId, invoiceDate: new Date("2026-10-27"), dueDate: new Date("2026-11-01"), items: [{ description: "Service", quantity: 1, unitPrice: 100, discount: 0, gstRate: 18 }] });
    expect(manual.poNumber).toBe(nextPo);
    const override = await createInvoice(tenantId, actorId, { customerId, subscriberId, poNumber: "INVOICE-ONLY", invoiceDate: new Date("2026-10-27"), dueDate: new Date("2026-11-01"), items: [{ description: "Service", quantity: 1, unitPrice: 100, discount: 0, gstRate: 18 }] });
    expect(override.poNumber).toBe("INVOICE-ONLY");
    expect((await updateInvoice(tenantId, actorId, override.id, { poNumber: "EDITED-PO" })).poNumber).toBe("EDITED-PO");
    expect((await updateInvoice(tenantId, actorId, override.id, { notes: "Keep PO" })).poNumber).toBe("EDITED-PO");
    expect((await updateInvoice(tenantId, actorId, override.id, { poNumber: "" })).poNumber).toBeNull();
    expect((await prisma.subscriber.findUniqueOrThrow({ where: { id: subscriberId } })).poNumber).toBe(nextPo);
    expect((await cancelInvoice(tenantId, actorId, override.id, "Test cancellation")).status).toBe("CANCELLED");
    await expect(updateInvoice(tenantId, actorId, override.id, { poNumber: "REJECT" })).rejects.toThrow("Only unpaid invoices");
    await expect(createInvoice(tenantId, actorId, { customerId: otherCustomerId, subscriberId, invoiceDate: new Date("2026-10-27"), dueDate: new Date("2026-11-01"), items: [{ description: "Service", quantity: 1, unitPrice: 100, discount: 0, gstRate: 18 }] })).rejects.toThrow("Subscriber not found");
    const pdf = await buildInvoicePdfBuffer(tenantId, next.id);
    mkdirSync("output/pdf", { recursive: true }); writeFileSync("output/pdf/subscriber-po-test.pdf", pdf.buffer);
    expect(pdf.buffer.subarray(0, 5).toString()).toBe("%PDF-");
  });
});
